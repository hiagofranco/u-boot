void cvx16_pinmux(u8 vendor)
{
	const struct ddr_pinmux *p;
	int i;

	for (p = ddr_pinmux; p < ddr_pinmux + ARRAY_SIZE(ddr_pinmux); p++) {
		if (p->vendor != vendor)
			continue;

		for (i = 0; i < ARRAY_SIZE(p->regs); i++)
			writel(p->regs[i], PHYD_BASE + i * 4);
		return;
	}
}
